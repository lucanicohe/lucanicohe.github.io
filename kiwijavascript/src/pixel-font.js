export function glyphFor(char) {
  return GLYPHS[char] ?? ['....', '....', '....', '....', '....', '....', '....'];
}

export function pixelTextWidth(text) {
  let width = 0;
  for (const char of text) width += char === ' ' ? 3 : 5;
  return width;
}

export function drawPixelText(ctx, text, left, top, pixelSize, color) {
  ctx.fillStyle = color;
  let x = 0;
  for (const char of text) {
    if (char === ' ') {
      x += 3;
      continue;
    }
    const glyph = glyphFor(char);
    for (let row = 0; row < glyph.length; row += 1) {
      for (let col = 0; col < 4; col += 1) {
        if (glyph[row][col] === '#') {
          ctx.fillRect(left + (x + col) * pixelSize, top + row * pixelSize, pixelSize, pixelSize);
        }
      }
    }
    x += 5;
  }
}
